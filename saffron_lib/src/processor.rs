use std::{
    io::Error,
    path::{Path, PathBuf},
};

use crate::types::*;

struct FileWithOffset<'a> {
    file_path: &'a Path,
    offset_hours: i32,
    offset_minutes: i32,
    offset_seconds: i32,
    offset_centiseconds: i32,
}
impl<'a> FileWithOffset<'a> {
    fn new(
        file_path: &'a Path,
        offset_hours: i32,
        offset_minutes: i32,
        offset_seconds: i32,
        offset_centiseconds: i32,
    ) -> Self {
        FileWithOffset {
            file_path,
            offset_hours,
            offset_minutes,
            offset_seconds,
            offset_centiseconds,
        }
    }
}

// TODO: 实现可以指定输出文件位置，而不是直接覆盖第一个文件
fn merge_ass_files_with_offsets(files: Vec<FileWithOffset>) -> Result<PathBuf, Error> {
    if files.is_empty() {
        return Err(Error::new(
            std::io::ErrorKind::InvalidInput,
            "No files provided for merging.",
        ));
    }
    let first_file = &files[0];
    let mut merged_ass = ASSFile::parse_from_file(&PathBuf::from(&first_file.file_path))?;

    for event in &mut merged_ass.events {
        event.adjust_time(
            first_file.offset_hours,
            first_file.offset_minutes,
            first_file.offset_seconds,
            first_file.offset_centiseconds,
            TimeAdjustTarget::Both,
        );
    }

    for file in &files[1..] {
        let path = PathBuf::from(&file.file_path);
        let mut ass_file = ASSFile::parse_from_file(&path)?;
        for event in &mut ass_file.events {
            event.adjust_time(
                file.offset_hours,
                file.offset_minutes,
                file.offset_seconds,
                file.offset_centiseconds,
                TimeAdjustTarget::Both,
            );
        }
        merged_ass.events.extend(ass_file.events);
    }
    merged_ass.write_to_file_buffered(&first_file.file_path.to_path_buf(), 4)?;
    Ok(first_file.file_path.to_path_buf())
}

